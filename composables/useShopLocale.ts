function detectInitialLanguage() {
  if (process.client) {
    return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
  }
  return 'en'
}

export function useShopLocale() {
  const langCookie = useCookie<ShopLang>('lang', {
    default: () => detectInitialLanguage(),
  })
  const lang = useState<ShopLang>('shop-lang', () => {
    const value = langCookie.value
    return value === 'zh' ? 'zh' : 'en'
  })

  watchEffect(() => {
    langCookie.value = lang.value
  })

  const setLang = (value: ShopLang) => {
    lang.value = value
    langCookie.value = value
  }

  const t = (key: keyof typeof messages.en) =>
    messages[lang.value][key] || messages.en[key]

  return {
    lang,
    isZh: computed(() => lang.value === 'zh'),
    t,
    setLang,
    messages,
  }
}
